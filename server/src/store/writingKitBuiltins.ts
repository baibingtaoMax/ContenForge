const WRITING_MD = `# 写作语言规范

一句话：**说理为主，演为辅。把观点讲透，用画面钩住读者。**

## 一、核心配比：80/20 语言法则

| 类型 | 占比 | 定义 | 作用 |
|------|------|------|------|
| **强势语言** | **40%** | **画面感 + 代入感** | 让读者身临其境、自动代入自己 |
| **陈述性语言** | **60%** | 讲道理、下定义、总结原理 | 把观点讲透、钉牢，撑起文章的认知密度 |

主旋律是"讲透"，画面是钩子和呼吸，说理才是主体。

## 二、强势语言 = 画面感 + 代入感（占 40%）

不是"咄咄逼人"，不是"下判断/给态度"，而是"让读者看见、让读者代入"。

1. **画面感**：用具体场景、细节、动作、对话，把抽象道理"演"出来。
   - ❌ 抽象说教："要保持情绪稳定。"
   - ✅ 画面："会议室里所有人都盯着他，对方甩来一句刁难。他端起杯子喝了口水，慢慢放下，才开口。"
2. **代入感**：用具体人物 + 具体场景，让读者自动对号入座。
   - ❌ 抽象："随叫随到会降低你的价值。"
   - ✅ 代入："他把消息秒回给每一个人，随叫随到。三个月后，没人再把他的话当回事。"

## 三、铁律：全程不用"你"

**一说"你"，就变成"我在对读者说教"，代入感立刻断裂。**

- ❌ "你有没有过这种时刻——消息秒回，结果对方越来越不当回事？"
- ✅ "他把消息秒回给每一个人。三个月后，没人再把他的话当回事。"

用"他/她"、第三人称的具体人物和场景，像放电影一样演出来。不点破、不指认，读者反而代入最深。

**例外**：认知对抗型文章（如文化自信篇）需要用"你"拉读者入场、建立对峙；情绪共鸣型严格不用"你"。两种打法分清楚。

## 四、陈述性语言（占 60%）

抽离出来下结论、给原理、下定义、做总结，是文章主体。要有锋利的判断、清晰的推演，提供认知密度，不泛泛而谈。每隔一段用画面托一下，让读者从密集说理中喘口气。
例："稀缺即价值，这是人性的底层逻辑。"

## 五、成稿自检清单

- 说理/定义/结论约占 60%，且讲得透、有认知密度？
- 画面/人物/场景/细节约占 40%，钩住读者、调节节奏？
- 是否通篇没有用"你"指认读者（认知对抗型除外）？
- 每个抽象观点都有画面托底，不让读者在纯说理里疲劳？
- 读者读完是"被一个观点说服、记住了"，而不只是"看了个故事"？
- 每个观点先演或先抛、再讲透，而不是只演不点破？`;

const TITLE_MD = `# 起标题方法论

**起标题不是才华题，是工程题。**

## 一、两层任务

1. **停手（点击率）**：让正在滑屏幕的人停下来、点进来。
2. **代言（转发率）**：标题本身是读者的态度宣言——转出去后标题=他想说的话，且"出现在朋友圈不丢人、还长脸"。

## 二、四把尺子（缺一不可）

1. **巨大的反差**：违背读者直觉、本能或常识。《如何处理负面情绪》→《什么都不做，比发泄和忍住都管用》
2. **打破现有认知**：点破他一直以为对、其实用错了的东西。"情绪要处理"→"情绪不用处理，找到就行"
3. **对他有利**：明确收益——更省力/更快/少受罪/有出口。
4. **转发代言**：转到朋友圈，是在告诉朋友"我是什么样的人"，且不丢人、还长脸。

> 有反差没认知=哗众取宠；有认知没反差=论文标题；没利益=文字游戏；没代言=叫座不叫好。四条全占=第一梯队。

## 三、动笔前必拆：认知爆破点

1. 读者现在怎么想/怎么做？（现有认知）
2. 文章打破的是什么？（认知反转）
3. 读者能得到什么好处？（利益点）
4. 转发后，他是在告诉朋友"他是什么样的人"？（代言身份）

## 四、三轴打法

- **A 反常识**：你以为 A，其实 B。"不是×××，是×××"/"越××越××"
- **B 戳体感**：说出他此刻身体/心里的真实感觉。"心口堵""攥紧""压不下去"
- **C 给动作**：给他一个立刻能做的小事。"先××，别××"

**最稳组合 = B+A**：先用具体身体感钩住，再翻认知。

## 五、技巧清单

- **具体 > 抽象**："心口那口气"比"负面情绪"有力 10 倍
- **口语 > 书面**：念出来不顺就改
- **动词是情绪开关**：中性词换带情绪、带指控、带立场的精准动词（源于→抄 / 利用→榨取 / 影响→操纵 / 选择→赌）
- **具体数字 > 模糊量词**："90%""3个""第1种"带来笃定感
- **"你"分打法**：认知对抗型标题用"你"拉入场；情绪共鸣型不用
- **主副配合**：主标题打反差，副标题补利益和方法

## 六、爆款案例

《你读的英文畅销书，90%抄自中国古籍》（四项数据第一）
- 反差：英文畅销书（高端）抄中国古籍（被鄙视），高位抄低位才是反转
- 破认知：默认"我们学西方"，翻成"西方在抄我们"
- 利益：饭局冷知识 + 文化优越感
- 代言：转发=我是有根的、不盲从西方的清醒者
- 四个机关："你读的"拉人入场 / "90%"数字笃定 / "抄"带指控 / 高低位错位

## 七、终极自检

- 是"感觉像个标题"，还是真的过了四把尺子？
- 读者脑子里有没有一个"啊？"的瞬间？
- 他会不会想转给某个具体的人？转了长脸还是丢人？

没有"啊？"、想不到转给谁、转了丢人 → 重起。`;

const SPREAD_MD = `# 读者反馈三维度框架

> **点赞是情绪的刻度，评论是表达欲的刻度，转发是身份认同的刻度。**
> 从左到右读者成本递增、传播价值递增。转发是传播引擎。

## 一、数据怎么读（不能只看数字高低）

- 点赞高、转发低 → "写得不错，但没人愿意代言"（共鸣够、身份感弱）
- 评论高、点赞低 → "吵起来了，但并不真正认同"（争议够、共识弱）
- 转发高、评论低 → "都在默默转，不敢公开讨论"（代言强、话题敏感）
- 三者全高 → 真爆款（共鸣+争议+代言同时成立）

## 二、转发动力（6 维）——选题与写作时最重要

1. **身份代言**："这篇代表我。"→ 立场鲜明，转完能"被识别"
2. **社交货币**："我先看到的。"→ 反常识、稀缺信息
3. **替我说话**："我早这么想但说不好。"→ 金句能直接当朋友圈文案
4. **立场站队**：争议话题公开选边 → 有对抗性、不和稀泥
5. **送人**："这篇对某某有用。"→ 有明确适用人群和场景
6. **自我收藏**："先转了回头看。"→ 硬价值（方法/清单/资料）

写作时必问：**读者转这篇，是在告诉朋友"我是什么样的人"？**

## 三、评论动力（6 维）

①反驳（最猛驱动力，观点要锋利）②补充/延伸（文章要留"开口"不封死）③强烈共鸣（拍大腿的句子）④自我展示（留公共讨论空间）⑤提问/求证（话只说一半的钩子）⑥情绪宣泄（给情绪出口）。

评论多 ≠ 好评多，但能引发讨论本身就是传播力；要盯评论区调性是否符合账号定位。

## 四、点赞动力（5 维）

①认同（最健康）②情绪触动 ③捧场/礼仪（弱信号）④标记（说明有硬价值）⑤习惯性随手（虚胖）。点赞门槛最低最易虚高，可参考但不能当核心指标。

## 五、发布前自检

- 读者转它是在说"我是什么人"？身份标签清晰吗？
- 有没有一句话能直接当朋友圈转发语？
- 读者读完会想到某个具体的人、想"该给他看看"吗？
- 有没有反常识/稀缺信息，让第一个转的人显得有见识？
- 观点锋利到有人想反驳吗？有没有留"开口"让人接力？
- 有没有被戳中的情绪点、让人想确认"我也是"的观点？

**一句话：值不值得被读者，转给他在乎的人？**

## 六、发布后复盘（24-48h）

- **转发率**（转发/阅读）：高=代言和社交货币成立；低="好但没人背书名"
- **评论率**（评论/阅读）：高=争议/表达欲被激发，看评论是骂、捧还是接力
- **点赞率**（点赞/阅读）：若远高于转发率="看完感动但不敢/不愿代言"`;

